"""Convert the pinned SVG sources into offline Core Graphics outlines.

Run with Python + fonttools. No runtime SVG parser or network is used by the app.
Only the selected brand mark is retained; website taglines and clip definitions
are excluded. Asset URLs and conversion details are recorded beside the SVG files.
"""
from pathlib import Path
import json
import xml.etree.ElementTree as ET
from fontTools.svgLib.path import parse_path
from fontTools.pens.recordingPen import RecordingPen
from fontTools.pens.boundsPen import BoundsPen

root = Path(__file__).resolve().parents[1]
folder = root / "Assets/BrandSources"
sources = json.loads((folder / "sources.json").read_text())
entries = []
manifest = []
for brand in ["nikon", "canon", "sony", "fujifilm", "leica", "hasselblad", "dji", "insta360"]:
    data = (folder / f"{brand}.svg").read_bytes()
    svg = ET.fromstring(data)
    layers = []
    # SVG assets are simple filled paths with no transforms.
    def visit(element, in_defs=False):
        tag = element.tag.split("}")[-1]
        in_defs = in_defs or tag in {"defs", "clipPath"}
        assert "transform" not in element.attrib
        if tag == "path" and not in_defs:
            if brand == "canon" and element.get("class") != "cls-3":
                return
            d = element.attrib["d"]
            bounds = BoundsPen(None)
            parse_path(d, bounds)
            if brand == "fujifilm" and bounds.bounds and bounds.bounds[1] >= 33:
                return
            pen = RecordingPen()
            parse_path(d, pen)
            tokens = []
            for operation, points in pen.value:
                command = {"moveTo": "M", "lineTo": "L", "curveTo": "C", "qCurveTo": "Q", "closePath": "Z", "endPath": "Z"}[operation]
                tokens.append(command)
                for point in points:
                    tokens.extend(f"{v:.5f}".rstrip("0").rstrip(".") if v else "0" for v in point)
            fill = element.get("fill", "#000000")
            if brand == "canon":
                fill = "#CC0000"
            if brand == "hasselblad":
                fill = "#000000"
            if fill == "white":
                fill = "#FFFFFF"
            if fill == "black":
                fill = "#000000"
            if len(fill) == 4:
                fill = "#" + "".join(c * 2 for c in fill[1:])
            layers.append((" ".join(tokens), fill.upper(), element.get("fill-rule") == "evenodd"))
        for child in element:
            visit(child, in_defs)
    visit(svg)
    assert layers
    body = ",\n".join(f'            layer("{color}", "{commands}"' + (', evenOdd: true)' if even_odd else ')') for commands, color, even_odd in layers)
    entries.append(f'        .{brand}: [\n{body}\n        ]')
    manifest.append({"brand": brand, "source": sources[brand], "layers": len(layers)})

header = '''// Generated by scripts/generate-brand-marks.py from Assets/BrandSources.
// Brand names and marks belong to their respective owners; see asset sources.
import AppKit

struct BrandVectorLayer {
    let path: CGPath
    let color: NSColor
    let evenOdd: Bool
}

enum BrandVectors {
    static let marks: [CameraBrand: [BrandVectorLayer]] = [
'''
footer = '''
    ]

    private static func layer(_ hex: String, _ commands: String, evenOdd: Bool = false) -> BrandVectorLayer {
        let tokens = commands.split(separator: " ")
        var index = 0
        func point() -> CGPoint {
            let x = Double(tokens[index])!, y = Double(tokens[index + 1])!
            index += 2
            return CGPoint(x: x, y: y)
        }
        let path = CGMutablePath()
        while index < tokens.count {
            let command = tokens[index]; index += 1
            switch command {
            case "M": path.move(to: point())
            case "L": path.addLine(to: point())
            case "C":
                let a = point(), b = point(), end = point()
                path.addCurve(to: end, control1: a, control2: b)
            case "Q":
                let control = point(), end = point()
                path.addQuadCurve(to: end, control: control)
            case "Z": path.closeSubpath()
            default: preconditionFailure("Invalid generated path")
            }
        }
        return BrandVectorLayer(path: path, color: PaletteColor(hex: hex)!.color, evenOdd: evenOdd)
    }
}
'''
(root / "Sources/FrameCore/BrandVectors.swift").write_text(header + ",\n".join(entries) + footer)
(folder / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
print("Generated", len(entries), "vector marks")
